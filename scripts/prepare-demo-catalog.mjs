/** Offline generator: no database connection, migration, secret or remote operation. */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { catalog, id, imageBytes, PROJECT_REF, ROOT, SEEDS } from './demo-catalog.mjs';
const quote=v=>typeof v==='number'?String(v):`'${String(v).replaceAll("'","''")}'`;

// One atomic DO statement owns all writes. The final SELECT uses only persistent
// tables and inline IDs, so it is safe even in a separate/autocommitted request.
export function buildDemoStatements(data, confirmedProjectRef = '') {
  if (confirmedProjectRef && confirmedProjectRef !== PROJECT_REF) throw new Error('Proyecto no autorizado.');
  const categories=data.categories.map(c=>({id:id('category:'+c.slug),name:c.name,slug:c.slug}));
  const products=data.products.map(p=>({id:p.id,category_slug:p.category_slug,name:p.name,slug:p.slug,description:p.description,price_cents:p.price_cents}));
  const variants=data.products.flatMap(p=>p.variants.map(v=>({...v,product_id:p.id})));
  const images=data.products.map(p=>({id:p.image.id,product_id:p.id,storage_path:p.image.storage_path,alt:p.image.alt,position:0}));
  const payloads=[categories,products,variants,images].map(rows=>JSON.stringify(rows));
  let tag='$vanta_demo$';
  while (payloads.some(payload=>payload.includes(tag))) tag=tag.replace(/\$$/,'_safe$');
  const records=(name,alias,columns)=>`jsonb_to_recordset(demo_${name}) as ${alias}(${columns})`;
  const c=alias=>records('categories',alias,'id uuid,name text,slug text');
  const p=alias=>records('products',alias,'id uuid,category_slug text,name text,slug text,description text,price_cents bigint');
  const v=alias=>records('variants',alias,'id uuid,product_id uuid,sku text,size text,color text');
  const i=alias=>records('images',alias,'id uuid,product_id uuid,storage_path text,alt text,position integer');
  const block=`-- GENERATED by npm run demo:prepare; edit catalog.demo.json, not this file.
-- Target: ${PROJECT_REF}; all prices/products/stock are fictional.
-- No remote operation is performed by the generator. Verify the Dashboard project.
-- For SQL Editor generate an explicitly confirmed file as documented in docs/demo-catalog-load.md.
-- One complete DO block, no temporary tables and no session SET/BEGIN/COMMIT dependency.
do ${tag}
declare
  confirmed_project_ref constant text := ${quote(confirmedProjectRef)};
  demo_categories constant jsonb := ${quote(payloads[0])}::jsonb;
  demo_products constant jsonb := ${quote(payloads[1])}::jsonb;
  demo_variants constant jsonb := ${quote(payloads[2])}::jsonb;
  demo_images constant jsonb := ${quote(payloads[3])}::jsonb;
begin
  if confirmed_project_ref <> '${PROJECT_REF}' then
    raise exception 'Falta confirmar el proyecto VANTA: generar el archivo con --confirm-project=${PROJECT_REF} --output=work/vanta-demo-load.sql';
  end if;
  -- This acknowledgement is NOT proof of database identity; verify Dashboard first.
  if not exists(select 1 from storage.buckets where id='product-images' and not public
    and file_size_limit=5242880 and 'image/png'=any(allowed_mime_types)) then
    raise exception 'Bucket privado incompatible; no se modifica su configuración';
  end if;
  lock table public.categories, public.products, public.product_variants,
    public.product_images, public.inventory in share row exclusive mode;
  if exists(select 1 from ${i('d')} where not exists(
    select 1 from storage.objects o where o.bucket_id='product-images' and o.name=d.storage_path)) then
    raise exception 'Faltan fotografías en Storage: se esperan rutas vanta-demo-v1/<modelo>/front.png';
  end if;

  insert into public.categories(id,name,slug,active)
  select id,name,slug,true from ${c('d')} on conflict do nothing;
  if (select count(*) from ${c('d')} join public.categories c
    on c.slug=d.slug and c.name=d.name and c.active) <> 4 then
    raise exception 'Colisión o categoría inactiva: no se sobrescriben categorías existentes';
  end if;

  insert into public.products(id,category_id,name,slug,description,price_cents,currency,active)
  select d.id,c.id,d.name,d.slug,d.description,d.price_cents,'ARS',true
  from ${p('d')} join public.categories c on c.slug=d.category_slug
  on conflict do nothing;
  if (select count(*) from ${p('d')} join public.categories c on c.slug=d.category_slug
    join public.products p on p.id=d.id and p.slug=d.slug and p.category_id=c.id
      and p.name=d.name and p.description=d.description and p.price_cents=d.price_cents and p.currency='ARS' and p.active) <> 8 then
    raise exception 'Colisión o producto demo alterado: transacción cancelada sin sobrescribir';
  end if;

  insert into public.product_variants(id,product_id,sku,size,color,active)
  select id,product_id,sku,size,color,true from ${v('d')} on conflict do nothing;
  if (select count(*) from ${v('d')} join public.product_variants v
    on v.id=d.id and v.product_id=d.product_id and v.sku=d.sku and v.size=d.size and v.color=d.color and v.active) <> 64 then
    raise exception 'Colisión o variante demo alterada: transacción cancelada';
  end if;

  insert into public.product_images(id,product_id,storage_path,alt,position)
  select id,product_id,storage_path,alt,position from ${i('d')} on conflict do nothing;
  if (select count(*) from ${i('d')} join public.product_images i
    on i.id=d.id and i.product_id=d.product_id and i.storage_path=d.storage_path and i.alt=d.alt and i.position=d.position) <> 8 then
    raise exception 'Colisión o imagen demo alterada: transacción cancelada';
  end if;

  -- Never restock existing rows or reset reservations on repetition.
  insert into public.inventory(variant_id,on_hand,reserved)
  select id,${data.on_hand_per_variant},0 from ${v('d')} on conflict (variant_id) do nothing;
end
${tag};
`;
  const ids=products.map(product=>`${quote(product.id)}::uuid`).join(',');
  const summary=`-- Independent read-only summary: no temporary or session state.
with demo_products(id) as (select unnest(array[${ids}]))
select
  (select count(*) from public.products p join demo_products d on p.id=d.id) as demo_products,
  (select count(*) from public.product_variants v join demo_products d on v.product_id=d.id) as demo_variants,
  (select count(*) from public.product_images i join demo_products d on i.product_id=d.id) as demo_images,
  (select count(*) from public.inventory i join public.product_variants v on v.id=i.variant_id
    join demo_products d on v.product_id=d.id) as demo_inventory_rows;
`;
  return [block,summary];
}
export const buildDemoSql=(data,confirmedProjectRef='')=>buildDemoStatements(data,confirmedProjectRef).join('\n');

export function runGenerator(args) {
  const check=args.includes('--check');
  const confirmation=args.find(a=>a.startsWith('--confirm-project='))?.slice('--confirm-project='.length) ?? '';
  const output=args.find(a=>a.startsWith('--output='))?.slice('--output='.length);
  if(args.some(a=>a!=='--check' && !a.startsWith('--confirm-project=') && !a.startsWith('--output='))) throw new Error('Argumentos no reconocidos.');
  if((confirmation || output) && (!confirmation || !output || check)) throw new Error('Usar --confirm-project y --output juntos, sin --check.');
  const path=output?resolve(ROOT,output):resolve(SEEDS,'catalog.example.sql');
  if(output && !path.startsWith(resolve(ROOT,'work')+'/')) throw new Error('El archivo confirmado solo puede generarse dentro de work/.');
  const data=catalog();
  const sql=buildDemoSql(data,confirmation);
  data.products.forEach(imageBytes);
  if(check) {
    if(readFileSync(path,'utf8')!==sql) throw new Error('SQL desactualizado: ejecutar npm run demo:prepare.');
    console.log('OK offline: SQL reproducible sin tablas temporales, ocho rutas/front.png y PNG íntegros, 64 variantes. Sin acceso remoto.');
  } else {
    mkdirSync(dirname(path),{recursive:true});
    writeFileSync(path,sql);
    console.log(`SQL generado localmente en ${path}. Confirmación ${confirmation?'incluida':'pendiente'}. No se ejecutó ninguna consulta.`);
  }
}
if(process.argv[1] && resolve(process.argv[1])===fileURLToPath(import.meta.url)) runGenerator(process.argv.slice(2));
