/** Offline generator: no database connection, migration, secret or remote operation. */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { catalog, id, imageBytes, PROJECT_REF, SEEDS } from './demo-catalog.mjs';
const data=catalog();
const quote=v=>typeof v==='number'?String(v):`'${String(v).replaceAll("'","''")}'`;
const values=rows=>rows.map(row=>'  ('+row.map(quote).join(', ')+')').join(',\n');
const categories=data.categories.map(c=>[id('category:'+c.slug),c.name,c.slug]);
const products=data.products.map(p=>[p.id,p.category_slug,p.name,p.slug,p.description,p.price_cents]);
const variants=data.products.flatMap(p=>p.variants.map(v=>[v.id,p.id,v.sku,v.size,v.color]));
const images=data.products.map(p=>[p.image.id,p.id,p.image.storage_path,p.image.alt,0]);
const sql=`-- GENERATED by npm run demo:prepare; edit catalog.demo.json, not this file.
-- PENDING APPROVAL: never run automatically or as a migration.
-- Target: ${PROJECT_REF}; all prices/products/stock are fictional.
-- Operator must FIRST verify the project in Dashboard, then explicitly run:
-- SET vanta.demo_project_ref = '${PROJECT_REF}';
-- This acknowledgement is NOT proof of database identity.
begin;
do $$ begin
  if current_setting('vanta.demo_project_ref', true) is distinct from '${PROJECT_REF}' then
    raise exception 'Falta confirmar el proyecto VANTA: revisar docs/demo-catalog-load.md';
  end if;
  if not exists(select 1 from storage.buckets where id='product-images' and not public
    and file_size_limit=5242880 and 'image/png'=any(allowed_mime_types)) then
    raise exception 'Bucket privado incompatible; no se modifica su configuración';
  end if;
end $$;
-- Serialize this short catalog transaction; no change to schemas, policies or grants.
lock table public.categories, public.products, public.product_variants,
  public.product_images, public.inventory in share row exclusive mode;
create temp table vanta_demo_categories(id uuid,name text,slug text) on commit drop;
insert into vanta_demo_categories values
${values(categories)};
create temp table vanta_demo_products(id uuid,category_slug text,name text,slug text,description text,price_cents bigint) on commit drop;
insert into vanta_demo_products values
${values(products)};
create temp table vanta_demo_variants(id uuid,product_id uuid,sku text,size text,color text) on commit drop;
insert into vanta_demo_variants values
${values(variants)};
create temp table vanta_demo_images(id uuid,product_id uuid,storage_path text,alt text,position integer) on commit drop;
insert into vanta_demo_images values
${values(images)};
do $$ begin
  if exists(select 1 from vanta_demo_images d where not exists(
    select 1 from storage.objects o where o.bucket_id='product-images' and o.name=d.storage_path)) then
    raise exception 'Faltan fotografías en Storage: subir/verificar primero los ocho archivos';
  end if;
end $$;
insert into public.categories(id,name,slug,active)
select id,name,slug,true from vanta_demo_categories on conflict do nothing;
do $$ begin
  if (select count(*) from vanta_demo_categories d join public.categories c
    on c.slug=d.slug and c.name=d.name and c.active) <> 4 then
    raise exception 'Colisión o categoría inactiva: no se sobrescriben categorías existentes';
  end if;
end $$;
insert into public.products(id,category_id,name,slug,description,price_cents,currency,active)
select d.id,c.id,d.name,d.slug,d.description,d.price_cents,'ARS',true
from vanta_demo_products d join public.categories c on c.slug=d.category_slug
on conflict do nothing;
do $$ begin
  if (select count(*) from vanta_demo_products d join public.categories c on c.slug=d.category_slug
    join public.products p on p.id=d.id and p.slug=d.slug and p.category_id=c.id
      and p.name=d.name and p.description=d.description and p.price_cents=d.price_cents and p.currency='ARS' and p.active) <> 8 then
    raise exception 'Colisión o producto demo alterado: transacción cancelada sin sobrescribir';
  end if;
end $$;
insert into public.product_variants(id,product_id,sku,size,color,active)
select id,product_id,sku,size,color,true from vanta_demo_variants on conflict do nothing;
do $$ begin
  if (select count(*) from vanta_demo_variants d join public.product_variants v
    on v.id=d.id and v.product_id=d.product_id and v.sku=d.sku and v.size=d.size and v.color=d.color and v.active) <> 64 then
    raise exception 'Colisión o variante demo alterada: transacción cancelada';
  end if;
end $$;
insert into public.product_images(id,product_id,storage_path,alt,position)
select id,product_id,storage_path,alt,position from vanta_demo_images on conflict do nothing;
do $$ begin
  if (select count(*) from vanta_demo_images d join public.product_images i
    on i.id=d.id and i.product_id=d.product_id and i.storage_path=d.storage_path and i.alt=d.alt and i.position=d.position) <> 8 then
    raise exception 'Colisión o imagen demo alterada: transacción cancelada';
  end if;
end $$;
-- Never restock existing rows or reset reservations on repetition.
insert into public.inventory(variant_id,on_hand,reserved)
select id,${data.on_hand_per_variant},0 from vanta_demo_variants on conflict (variant_id) do nothing;
select
  (select count(*) from vanta_demo_products) as demo_products,
  (select count(*) from vanta_demo_variants) as demo_variants,
  (select count(*) from vanta_demo_images) as demo_images,
  (select count(*) from public.inventory i join vanta_demo_variants v on v.id=i.variant_id) as demo_inventory_rows;
commit;
`;
const path=resolve(SEEDS,'catalog.example.sql');
if(process.argv.includes('--check')) {
  if(readFileSync(path,'utf8')!==sql) throw new Error('SQL desactualizado: ejecutar npm run demo:prepare.');
  data.products.forEach(imageBytes);
  console.log('OK offline: SQL reproducible, ocho PNG íntegros, 64 variantes. Sin acceso remoto.');
} else {
  writeFileSync(path,sql);
  console.log('SQL generado localmente. No se ejecutó ninguna consulta.');
}
